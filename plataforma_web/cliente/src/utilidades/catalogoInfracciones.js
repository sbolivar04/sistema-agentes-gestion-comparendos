/**
 * Normaliza cualquier código de infracción al formato canónico (Letra mayúscula + 2 dígitos).
 * Ejemplos:
 *  - 'D4'  -> 'D04'
 *  - 'd04' -> 'D04'
 *  - 'C2'  -> 'C02'
 *  - 'c29' -> 'C29'
 */
export function normalizarCodigoInfraccion(codigo) {
  if (!codigo) return ''
  const texto = String(codigo).trim().toUpperCase()
  const coincidencia = texto.match(/\b([A-Z])\s*0*(\d{1,2})\b/)
  if (coincidencia) {
    const letra = coincidencia[1]
    const numero = parseInt(coincidencia[2], 10)
    return `${letra}${numero < 10 ? '0' + numero : numero}`
  }
  return texto
}

/**
 * Retorna la descripción oficial si el código existe en el catálogo nacional.
 */
export function obtenerDescripcionOficialInfraccion(codigo) {
  const codigoLimpio = normalizarCodigoInfraccion(codigo)
  if (!codigoLimpio) return null
  return DICCIONARIO_INFRACCIONES_COLOMBIA[codigoLimpio] || null
}

/**
 * Función principal para interfaz de usuario.
 * Retorna la descripción oficial legal prioritaria.
 * Si no está en el catálogo, rescata la descripción actual si es informativa y válida.
 */
export function obtenerDescripcionInfraccion(codigo, descripcionActual) {
  const descripcionOficial = obtenerDescripcionOficialInfraccion(codigo)
  if (descripcionOficial) {
    return descripcionOficial
  }

  const descLimpia = String(descripcionActual || '').trim()
  if (
    descLimpia &&
    !descLimpia.toLowerCase().includes('reportada en simit') &&
    descLimpia.toUpperCase() !== 'COMPARENDO'
  ) {
    return descLimpia
  }

  const codNorm = normalizarCodigoInfraccion(codigo)
  return codNorm ? `Infracción ${codNorm}` : 'Infracción de tránsito'
}
